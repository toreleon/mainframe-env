pub(super) const fn output_tag(value: CicsOutputName) -> u16 {
    match value {
        CicsOutputName::Into => 0,
        CicsOutputName::Resp => 1,
        CicsOutputName::Resp2 => 2,
        CicsOutputName::Abstime => 3,
        CicsOutputName::Field => 696,
        CicsOutputName::DigestResult => 697,
        CicsOutputName::OperatorReply => 698,
        CicsOutputName::OperatorReplyLength => 699,
        CicsOutputName::Certificate(output) => output.tag(),
        CicsOutputName::Tcpip(output) => output.tag(),
        CicsOutputName::Milliseconds => 4,
        CicsOutputName::Mmddyy => 5,
        CicsOutputName::Mmddyyyy => 6,
        CicsOutputName::Time => 7,
        CicsOutputName::Yyddd => 8,
        CicsOutputName::Yymmdd => 9,
        CicsOutputName::Yyyymmdd => 10,
        CicsOutputName::Commarea => 11,
        CicsOutputName::Ridfld => 12,
        CicsOutputName::Token => 240,
        CicsOutputName::Assign(output) => {
            let tag = output.tag() as u16;
            if tag < ASSIGN_OUTPUT_LEGACY_COUNT {
                ASSIGN_OUTPUT_TAG_BASE + tag
            } else {
                ASSIGN_OUTPUT_EXTENSION_TAG_BASE + (tag - ASSIGN_OUTPUT_LEGACY_COUNT)
            }
        }
        CicsOutputName::Length => 91,
        CicsOutputName::ReturnTransId => 92,
        CicsOutputName::ReturnTermId => 93,
        CicsOutputName::Queue => 94,
        CicsOutputName::SetPointer => 95,
        CicsOutputName::NumItems => 200,
        CicsOutputName::DocumentToken => 216,
        CicsOutputName::DocumentSize => 217,
        CicsOutputName::ElementName => 224,
        CicsOutputName::ElementNameLength => 225,
        CicsOutputName::ElementNamespace => 226,
        CicsOutputName::ElementNamespaceLength => 227,
        CicsOutputName::TypeName => 228,
        CicsOutputName::TypeNameLength => 229,
        CicsOutputName::TypeNamespace => 230,
        CicsOutputName::TypeNamespaceLength => 231,
        CicsOutputName::JournalReqId => 201,
        CicsOutputName::SetPointer64 => 232,
        CicsOutputName::SpoolToken => 208,
        CicsOutputName::SpoolToFlength => 209,
    }
}

pub(super) fn output_from_tag(value: u16) -> Result<CicsOutputName, CicsPlanCodecProblem> {
    match value {
        0 => Ok(CicsOutputName::Into),
        1 => Ok(CicsOutputName::Resp),
        2 => Ok(CicsOutputName::Resp2),
        3 => Ok(CicsOutputName::Abstime),
        696 => Ok(CicsOutputName::Field),
        697 => Ok(CicsOutputName::DigestResult),
        698 => Ok(CicsOutputName::OperatorReply),
        699 => Ok(CicsOutputName::OperatorReplyLength),
        700..=716 => CicsCertificateOutput::from_tag(value)
            .map(CicsOutputName::Certificate)
            .ok_or(CicsPlanCodecProblem::Malformed),
        717..=737 => CicsTcpipOutput::from_tag(value)
            .map(CicsOutputName::Tcpip)
            .ok_or(CicsPlanCodecProblem::Malformed),
        4 => Ok(CicsOutputName::Milliseconds),
        5 => Ok(CicsOutputName::Mmddyy),
        6 => Ok(CicsOutputName::Mmddyyyy),
        7 => Ok(CicsOutputName::Time),
        8 => Ok(CicsOutputName::Yyddd),
        9 => Ok(CicsOutputName::Yymmdd),
        10 => Ok(CicsOutputName::Yyyymmdd),
        11 => Ok(CicsOutputName::Commarea),
        12 => Ok(CicsOutputName::Ridfld),
        240 => Ok(CicsOutputName::Token),
        91 => Ok(CicsOutputName::Length),
        92 => Ok(CicsOutputName::ReturnTransId),
        93 => Ok(CicsOutputName::ReturnTermId),
        94 => Ok(CicsOutputName::Queue),
        95 => Ok(CicsOutputName::SetPointer),
        200 => Ok(CicsOutputName::NumItems),
        216 => Ok(CicsOutputName::DocumentToken),
        217 => Ok(CicsOutputName::DocumentSize),
        224 => Ok(CicsOutputName::ElementName),
        225 => Ok(CicsOutputName::ElementNameLength),
        226 => Ok(CicsOutputName::ElementNamespace),
        227 => Ok(CicsOutputName::ElementNamespaceLength),
        228 => Ok(CicsOutputName::TypeName),
        229 => Ok(CicsOutputName::TypeNameLength),
        230 => Ok(CicsOutputName::TypeNamespace),
        231 => Ok(CicsOutputName::TypeNamespaceLength),
        201 => Ok(CicsOutputName::JournalReqId),
        232 => Ok(CicsOutputName::SetPointer64),
        208 => Ok(CicsOutputName::SpoolToken),
        209 => Ok(CicsOutputName::SpoolToFlength),
        13..=90 => CicsAssignOutput::from_tag((value - ASSIGN_OUTPUT_TAG_BASE) as u8)
            .map(CicsOutputName::Assign)
            .ok_or(CicsPlanCodecProblem::Malformed),
        // Reserved non-ASSIGN journal outputs must remain ahead of the
        // open-ended ASSIGN extension decoder.
        202..=207 => Err(CicsPlanCodecProblem::Malformed),
        96..=u16::MAX => value
            .checked_sub(ASSIGN_OUTPUT_EXTENSION_TAG_BASE)
            .and_then(|tag| tag.checked_add(ASSIGN_OUTPUT_LEGACY_COUNT))
            .and_then(|tag| u8::try_from(tag).ok())
            .and_then(CicsAssignOutput::from_tag)
            .map(CicsOutputName::Assign)
            .ok_or(CicsPlanCodecProblem::Malformed),
    }
}
